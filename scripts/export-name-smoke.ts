import { _electron as electron, expect } from '@playwright/test'
import { mkdir, mkdtemp, readFile, stat } from 'node:fs/promises'
import { resolve, join } from 'node:path'
import sharp from 'sharp'

async function main() {
  await mkdir('.test-output', { recursive: true })
  const output = await mkdtemp(resolve('.test-output/export-name-'))
  const source = join(output, 'source.jpg')
  await sharp({ create: { width: 369, height: 248, channels: 3, background: '#71836c' } }).withIccProfile('srgb').jpeg().toFile(source)
  const original = await readFile(source)
  const env = Object.fromEntries(Object.entries(process.env).filter((e): e is [string, string] => e[1] !== undefined))
  env.PDIMPRESSION_TEST = '1'; delete env.ELECTRON_RUN_AS_NODE
  const desktop = await electron.launch({ args: [resolve('out/main/index.js'), `--user-data-dir=${join(output, 'user-data')}`], env })
  try {
    const page = await desktop.firstWindow()
    page.setDefaultTimeout(15000)
    await page.getByRole('button', { name: '选择 135', exact: true }).click()
    await desktop.evaluate(({ dialog }, source) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [source] }) }, source)
    await page.getByRole('button', { name: '导入照片', exact: true }).click()
    await expect(page.locator('.photo-row')).toHaveCount(1)
    await page.getByLabel('订单编号 / 拍摄者').fill('NAME-001')
    await page.getByRole('button', { name: '导出接触印象 ↗', exact: true }).click()
    const name = page.getByLabel('导出文件名', { exact: true })
    const submit = page.getByRole('button', { name: '选择文件夹并导出 ↗', exact: true })
    await expect(name).toHaveValue('NAME-001_索引_高清_8000px')
    await page.getByLabel('高清输出宽度').selectOption('6000')
    await expect(name).toHaveValue('NAME-001_索引_高清_6000px')
    await name.fill('../outside')
    await expect(submit).toBeDisabled()
    await name.fill('')
    await expect(submit).toBeDisabled()
    await page.getByRole('button', { name: '恢复默认命名' }).click()
    await expect(name).toHaveValue('NAME-001_索引_高清_6000px')
    await name.fill('冷静_胶卷预览.jpg')
    await expect(page.locator('.export-filename-help')).toContainText('将保存为：冷静_胶卷预览.jpg')
    await page.getByRole('button', { name: '关闭', exact: true }).click()
    await page.getByRole('button', { name: '导出接触印象 ↗', exact: true }).click()
    await expect(name).toHaveValue('冷静_胶卷预览.jpg')
    await page.getByRole('dialog', { name: '导出索引图' }).screenshot({ path: join(output, 'export-dialog.png') })
    await desktop.evaluate(({ dialog }, folder) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [folder] }) }, output)
    await submit.click()
    await expect(page.locator('.task-card').filter({ hasText: '导出完成' })).toBeVisible({ timeout: 120000 })
    const destination = join(output, '冷静_胶卷预览.jpg')
    expect((await sharp(destination).metadata()).width).toBe(6000)
    expect((await stat(destination)).size).toBeLessThanOrEqual(25_000_000)
    const exported = await readFile(destination)
    await desktop.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 0, checkboxChecked: false }) })
    await page.getByRole('button', { name: '导出接触印象 ↗', exact: true }).click()
    await submit.click()
    await expect(page.locator('.task-card').filter({ hasText: '已取消' })).toBeVisible()
    expect(await readFile(destination)).toEqual(exported)
    await page.getByRole('button', { name: '导出接触印象 ↗', exact: true }).click()
    await name.fill('source')
    await submit.click()
    await expect(page.locator('.task-card').filter({ hasText: '原图不能被覆盖' })).toBeVisible()
    expect(await readFile(source)).toEqual(original)
    console.log(`Export naming passed: custom JPEG, default/reset, invalid names, overwrite cancellation and source protection. Screenshot: ${join(output, 'export-dialog.png')}`)
  } finally {
    await desktop.evaluate(({ app }) => app.exit(0)).catch(() => {})
    await desktop.close().catch(() => {})
  }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
